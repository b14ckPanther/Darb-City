export const adminCopy: Record<Locale, Messages> = { he, ar, en };

export function at(
  locale: Locale,
  key: AdminKey,
  vars: Record<string, string | number> = {},
): string {
  return adminCopy[locale][key].replace(/\{(\w+)\}/g, (m, name: string) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : m,
  );
}
