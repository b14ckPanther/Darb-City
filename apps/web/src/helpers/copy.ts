export const helperCopy: Record<Locale, Messages> = { he, ar, en };

export function ht(
  locale: Locale,
  key: HelperKey,
  vars: Record<string, string | number> = {},
): string {
  return helperCopy[locale][key].replace(/\{(\w+)\}/g, (m, name: string) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : m,
  );
}
